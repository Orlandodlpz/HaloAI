"""Copy the badge's font into the demo site, so its e-ink screen draws the same pixels (B6).

Reads the glyph tables the firmware uses (firmware/board/main/fonts/*.hpp, generated by
firmware/tools/bdf_to_c.py from Spleen, BSD 2-Clause) and writes pipeline/site/glyphs.js.
Only reads Victor's files. Run again whenever the firmware font changes:

    cd pipeline && .venv/bin/python scripts/build_glyphs.py
"""

import base64
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "firmware/board/main/fonts"
SITE = ROOT / "pipeline/site"


def parse(path: Path, prefix: str) -> dict:
    src = path.read_text()

    def const(name: str) -> int:
        return int(re.search(rf"k{prefix}{name}\s*=\s*(\d+)", src).group(1))
    body = src[src.index(f"k{prefix}Glyphs"):]
    rows = re.findall(r"\{([^{}]*)\}", body)
    data = b"".join(bytes(int(b, 16) for b in re.findall(r"0x([0-9a-fA-F]{2})", row)) for row in rows)
    w, h, stride, first, last = (const(n) for n in ("Width", "Height", "Stride", "First", "Last"))
    if len(data) != (last - first + 1) * h * stride:
        raise SystemExit(f"{path.name}: expected {(last - first + 1) * h * stride} bytes, got {len(data)}")
    return {"w": w, "h": h, "stride": stride, "first": first, "last": last,
            "data": base64.b64encode(data).decode()}


def main() -> None:
    body = parse(FONTS / "font_body.hpp", "Body")
    status = parse(FONTS / "font_status.hpp", "Status")
    out = ("// Generated by pipeline/scripts/build_glyphs.py from the firmware's font tables. Do not edit.\n"
           "// Font: Spleen by Frederic Cambus, BSD 2-Clause (LICENSE.spleen). One bit per pixel, rows top\n"
           "// to bottom, most significant bit leftmost, a set bit is ink: the same bytes the badge draws.\n"
           f"export const FONTS = {json.dumps({'body': body, 'status': status})};\n")
    (SITE / "glyphs.js").write_text(out)
    shutil.copy(ROOT / "firmware/tools/LICENSE.spleen", SITE / "LICENSE.spleen")
    print(f"wrote {SITE / 'glyphs.js'}: body {body['w']}x{body['h']}, status {status['w']}x{status['h']}, "
          f"{body['last'] - body['first'] + 1} glyphs each")


if __name__ == "__main__":
    main()
