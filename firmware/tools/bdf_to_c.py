#!/usr/bin/env python3
"""Turn a Spleen BDF into a C glyph table, and render a preview of a real screen.

Two jobs on purpose: the preview is rendered from the SAME glyph bytes the
firmware will use, so what you look at is what the panel will draw. Without that
the font choice is guesswork until the badge arrives.

  python3 bdf_to_c.py spleen-16x32.bdf --name body --out font_body.hpp
  python3 bdf_to_c.py spleen-16x32.bdf --preview badge.png --panel badge
"""
import argparse, struct, zlib

FIRST, LAST = 32, 126  # printable ASCII; the device never shows anything else


def parse_bdf(path):
    glyphs, w, h, enc, rows, in_bitmap = {}, 0, 0, None, [], False
    for line in open(path, encoding="latin-1"):
        line = line.strip()
        if line.startswith("FONTBOUNDINGBOX"):
            _, w, h, _, _ = line.split()
            w, h = int(w), int(h)
        elif line.startswith("ENCODING"):
            enc = int(line.split()[1])
        elif line == "BITMAP":
            in_bitmap, rows = True, []
        elif line == "ENDCHAR":
            if enc is not None and FIRST <= enc <= LAST:
                glyphs[enc] = rows
            in_bitmap, enc = False, None
        elif in_bitmap:
            rows.append(line)
    return w, h, glyphs


def to_c(name, w, h, glyphs):
    stride = (w + 7) // 8
    out = [
        "// Generated by firmware/tools/bdf_to_c.py. Do not edit by hand.",
        "// Font: Spleen by Frederic Cambus, BSD 2-Clause. See firmware/tools/LICENSE.spleen",
        "//",
        "// One bit per pixel, rows top to bottom, most significant bit leftmost,",
        "// each row padded to whole bytes. A set bit is ink.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace halo::font {",
        "",
        f"constexpr uint8_t k{name}Width = {w};",
        f"constexpr uint8_t k{name}Height = {h};",
        f"constexpr uint8_t k{name}First = {FIRST};",
        f"constexpr uint8_t k{name}Last = {LAST};",
        f"constexpr uint16_t k{name}Stride = {stride};",
        "",
        f"constexpr uint8_t k{name}Glyphs[][{stride * h}] = {{",
    ]
    for code in range(FIRST, LAST + 1):
        rows = glyphs.get(code, ["0" * (stride * 2)] * h)
        byts = []
        for r in rows[:h]:
            v = int(r, 16)
            byts.extend(((v >> (8 * (stride - 1 - i))) & 0xFF) for i in range(stride))
        while len(byts) < stride * h:
            byts.append(0)
        ch = chr(code).replace("\\", "\\\\").replace("'", "\\'")
        out.append("    {" + ", ".join(f"0x{b:02x}" for b in byts) + f"}},  // '{ch}'")
    out += ["};", "", "}  // namespace halo::font", ""]
    return "\n".join(out)


def write_png(path, w, h, px):
    """px: bytearray of w*h, 0 = black ink, 255 = white."""
    raw = b"".join(b"\x00" + bytes(px[y * w:(y + 1) * w]) for y in range(h))

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    hdr = struct.pack(">IIBBBBB", w, h, 8, 0, 0, 0, 0)
    open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", hdr)
                           + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


class Canvas:
    def __init__(self, w, h):
        self.w, self.h, self.px = w, h, bytearray([255] * (w * h))

    def set(self, x, y, v=0):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.px[y * self.w + x] = v

    def rect(self, x, y, w, h, v=0):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.set(xx, yy, v)

    def text(self, s, x, y, fw, fh, glyphs, invert=False):
        stride = (fw + 7) // 8
        for i, ch in enumerate(s):
            rows = glyphs.get(ord(ch))
            if rows is None:
                continue
            for ry, r in enumerate(rows[:fh]):
                v = int(r, 16)
                for bx in range(fw):
                    on = (v >> (stride * 8 - 1 - bx)) & 1
                    if invert:
                        on = not on
                    if on:
                        self.set(x + i * fw + bx, y + ry, 0)


# Layout constants, mirrored from firmware/core/src/layout.cpp.
MARGIN, STATUS_H, DIVIDER_Y, BODY_TOP, FOOTER_H = 16, 40, 44, 56, 36

PANELS = {"badge": (800, 480, 480), "crowpanel": (800, 480, 272)}


def preview(path, panel, body, status):
    lw, lh, vis = PANELS[panel]
    bw, bh, bg = body
    sw, sh, sg = status
    c = Canvas(lw, vis)
    c.text("Ready to confirm", MARGIN, (STATUS_H - sh) // 2, sw, sh, sg)
    c.rect(MARGIN, DIVIDER_Y, lw - 2 * MARGIN, 2)
    lines = [
        "To: victor.munozvera01@utrgv.edu",
        "Subject: Meeting moved to Thursday",
        "",
        "Hi Victor, the meeting moved to",
        "Thursday at 3 pm. Let me know if",
        "that does not work for you.",
        "",
        "Thanks, Carlos",
    ]
    room = (vis - BODY_TOP - FOOTER_H) // bh
    for i, line in enumerate(lines[:room]):
        c.text(line, MARGIN, BODY_TOP + i * bh, bw, bh, bg)
    c.text("press to send, double press to cancel", MARGIN, vis - FOOTER_H + 4, sw, sh, sg)
    write_png(path, lw, vis, c.px)
    print(f"{path}: {lw}x{vis}, body {lw - 2 * MARGIN}/{bw} = "
          f"{(lw - 2 * MARGIN) // bw} cols x {room} lines")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("bdf")
    ap.add_argument("--name")
    ap.add_argument("--out")
    ap.add_argument("--preview")
    ap.add_argument("--panel", default="badge")
    ap.add_argument("--status-bdf")
    a = ap.parse_args()
    w, h, g = parse_bdf(a.bdf)
    if a.out:
        open(a.out, "w").write(to_c(a.name, w, h, g))
        print(f"{a.out}: {len(g)} glyphs, {w}x{h}")
    if a.preview:
        sw, sh, sg = (parse_bdf(a.status_bdf) + (None,))[:3] if a.status_bdf else (w, h, g)
        sw, sh, sg = (sw, sh, sg) if a.status_bdf else (w, h, g)
        preview(a.preview, a.panel, (w, h, g), (sw, sh, sg))
